// Generate a single-file homepage preview for viewers without relative asset support.
// The production pages continue to share assets/css/style.css and assets/js/main.js.
const fs = require('node:fs');
let html = fs.readFileSync('index.html', 'utf8');
const css = fs.readFileSync('assets/css/style.css', 'utf8');
const js = fs.readFileSync('assets/js/main.js', 'utf8');
html = html.replace('<link rel="stylesheet" href="assets/css/style.css">', () => `<style>\n${css}\n</style>`);
html = html.replace('<script src="assets/js/main.js"></script>', () => `<script>\n${js}\n</script>`);
html = html.replace('const p = location.pathname.split("/").pop();', 'const p = "index.html";');
fs.writeFileSync('preview.html', '<!-- Generated by node preview.cjs. Edit the shared source files. -->\n' + html);
if (!html.includes('<style>') || /(?:href|src)="assets\//.test(html)) {
  throw new Error('Preview still depends on local assets');
}
console.log('Created preview.html with embedded CSS and JavaScript.');
